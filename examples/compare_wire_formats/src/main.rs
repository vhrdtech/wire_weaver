//! Wire size of one message set in `shrink_wrap` and eight other pure-Rust formats (EX-20).
//!
//! Every message in `msgs/` is encoded by every format at the setting a project would pick to be small; the
//! tables in `docs/generated/compare_wire_formats/` come from here and are stale-checked by `book_output`.

use rows::{Message, Row};
use std::fmt::Write as _;

mod asn1;
mod book_output;
mod chart;
#[expect(
    dead_code,
    clippy::enum_variant_names,
    reason = "generated by planus: builders and readers are unused, variants repeat the union name"
)]
mod fbs_messages;
#[expect(
    dead_code,
    reason = "generated by planus: builders and readers are unused"
)]
mod fbs_request;
mod msgs;
mod rows;

/// Bytes of a transcript line before it is cut: the firmware chunk would fill a page otherwise.
const SHOWN_BYTES_MAX: usize = 48;

fn smallest(rows: &[Row]) -> usize {
    rows.iter()
        .map(|row| row.bytes.len())
        .min()
        .expect("every message has rows")
}

fn transcript(message: &Message) -> String {
    let mut text = String::new();
    for row in &message.rows {
        let shown = &row.bytes[..row.bytes.len().min(SHOWN_BYTES_MAX)];
        let cut = if row.bytes.len() > SHOWN_BYTES_MAX {
            " .."
        } else {
            ""
        };
        writeln!(
            text,
            "{}: len: {}: {shown:02X?}{cut}",
            row.format,
            row.bytes.len()
        )
        .expect("writing to a String");
    }
    text
}

fn table(message: &Message) -> String {
    let best = smallest(&message.rows);
    let mut csv = String::from("format,bytes,evolution,smallest\n");
    for row in &message.rows {
        let mark = if row.bytes.len() == best { "yes" } else { "" };
        writeln!(
            csv,
            "{},{},{},{mark}",
            row.format,
            row.bytes.len(),
            row.evolution.as_str()
        )
        .expect("writing to a String");
    }
    csv
}

/// Formats down, messages across: each cell is the byte count.
fn matrix(messages: &[Message]) -> String {
    let mut csv = String::from("format");
    for message in messages {
        write!(csv, ",{}", message.name).expect("writing to a String");
    }
    csv.push('\n');
    for (i, first) in messages[0].rows.iter().enumerate() {
        write!(csv, "{}", first.format).expect("writing to a String");
        for message in messages {
            let row = &message.rows[i];
            assert_eq!(
                row.format, first.format,
                "every message lists the formats in the same order"
            );
            write!(csv, ",{}", row.bytes.len()).expect("writing to a String");
        }
        csv.push('\n');
    }
    csv
}

/// Per message: the smallest format, and where each `WireWeaver` row stands.
fn winners(messages: &[Message]) -> String {
    let mut csv = String::from("message,smallest,bytes,wireweaver_plain,wireweaver_tuned\n");
    for message in messages {
        let best = smallest(&message.rows);
        let names: Vec<&str> = message
            .rows
            .iter()
            .filter(|row| row.bytes.len() == best)
            .map(|row| row.format)
            .collect();
        writeln!(
            csv,
            "{},{},{best},{},{}",
            message.name,
            names.join(" / "),
            message.rows[0].bytes.len(),
            message.rows[1].bytes.len()
        )
        .expect("writing to a String");
    }
    csv
}

fn main() {
    let messages = msgs::all();
    for message in &messages {
        let text = transcript(message);
        print!("== {}\n{text}", message.title);
        book_output::check(&format!("compare_wire_formats/{}.txt", message.name), &text);
        book_output::check(
            &format!("compare_wire_formats/{}.csv", message.name),
            &table(message),
        );
    }
    book_output::check("compare_wire_formats/summary.csv", &matrix(&messages));
    book_output::check("compare_wire_formats/winners.csv", &winners(&messages));
    book_output::check(
        "compare_wire_formats/wire_sizes.svg",
        &chart::svg(&messages),
    );
}
