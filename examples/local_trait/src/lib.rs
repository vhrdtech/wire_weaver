//! One API used two ways (CLT-57): [exercise] is written once against the [Counter] trait and runs against
//! [LocalCounter], a plain struct called directly (no server, no serialization, no channel), and against
//! [client::CounterClient], the generated client talking to a device or service.
//!
//! [server::CounterServer] shows the other direction (SRV-49): `serve_trait` generates every handler, each
//! forwarding to one shared [LocalCounter], served to many clients on `wire_weaver_server`, so the logic is written
//! once and served remotely when needed.

mod locked;

use crate::locked::Locked;
use futures_lite::StreamExt;
use local_trait_api::{Counter, CounterError, SnapshotOwned};
use std::sync::Mutex;
use tokio::sync::broadcast;
use wire_weaver::call::{CallError, Error, ErrorKind, ItemStream, item_stream};
use wire_weaver::{CallContext, Peer};

/// The counter in this process: a plain struct implementing [Counter].
pub struct LocalCounter {
    name: String,
    state: Mutex<State>,
    totals: broadcast::Sender<u32>,
}

struct State {
    total: u32,
    step: u32,
}

impl LocalCounter {
    pub fn new(name: &str) -> Self {
        Self {
            name: name.to_string(),
            state: Mutex::new(State { total: 0, step: 1 }),
            totals: broadcast::channel(16).0,
        }
    }
}

impl Counter for LocalCounter {
    async fn add(&self, _cx: &CallContext, by: u32) -> Result<u32, Error> {
        let total = {
            let mut state = self.state.locked();
            state.total = state.total.wrapping_add(by.wrapping_mul(state.step));
            state.total
        };
        // nobody listening is fine
        let _ = self.totals.send(total);
        Ok(total)
    }

    async fn split(&self, _cx: &CallContext, parts: u32) -> Result<u32, CallError<CounterError>> {
        if parts == 0 {
            return Err(CallError::Api(CounterError::DivByZero));
        }
        Ok(self.state.locked().total / parts)
    }

    async fn snapshot(&self, _cx: &CallContext) -> Result<SnapshotOwned, Error> {
        let state = self.state.locked();
        Ok(SnapshotOwned {
            name: self.name.clone(),
            total: state.total,
            step: state.step,
        })
    }

    async fn read_step(&self, _cx: &CallContext) -> Result<u32, Error> {
        Ok(self.state.locked().step)
    }

    async fn write_step(&self, cx: &CallContext, step: u32) -> Result<(), Error> {
        // a policy reads who asked, the same behind a server and in the same process
        if let Peer::Addr(addr) = cx.peer {
            return Err(Error::denied(format!(
                "{addr}: the step is not set over the network"
            )));
        }
        self.state.locked().step = step;
        Ok(())
    }

    async fn totals(&self, _cx: &CallContext) -> Result<ItemStream<u32>, Error> {
        let rx = self.totals.subscribe();
        Ok(item_stream(futures_lite::stream::unfold(
            rx,
            |mut rx| async move {
                match rx.recv().await {
                    Ok(total) => Some((Ok(total), rx)),
                    Err(broadcast::error::RecvError::Closed) => None,
                    // fell behind: the stream's queue was full, like a device stream's on the host
                    Err(broadcast::error::RecvError::Lagged(_)) => {
                        Some((Err(ErrorKind::Overloaded.into()), rx))
                    }
                }
            },
        )))
    }
}

/// What [exercise] saw.
#[derive(Debug, PartialEq, Eq)]
pub struct Report {
    pub totals: Vec<u32>,
    pub step: u32,
    pub half: u32,
    pub div_by_zero: bool,
    pub snapshot: SnapshotOwned,
}

/// The call site, written once: the same code drives a [LocalCounter] and a remote counter.
pub async fn exercise(
    counter: &impl Counter,
    cx: &CallContext,
) -> Result<Report, Box<dyn std::error::Error>> {
    let mut totals = counter.totals(cx).await?;
    counter.write_step(cx, 2).await?;
    let step = counter.read_step(cx).await?;
    counter.add(cx, 3).await?;
    counter.add(cx, 1).await?;
    let half = counter.split(cx, 2).await?;
    let div_by_zero = matches!(
        counter.split(cx, 0).await,
        Err(CallError::Api(CounterError::DivByZero))
    );
    let snapshot = counter.snapshot(cx).await?;
    let mut seen = vec![];
    for _ in 0..2 {
        match totals.next().await {
            Some(total) => seen.push(total?),
            None => break,
        }
    }
    Ok(Report {
        totals: seen,
        step,
        half,
        div_by_zero,
        snapshot,
    })
}

/// A server of the shared [LocalCounter], every handler generated by `serve_trait` (SRV-49): the same
/// implementation in-process callers use, served to many clients on `wire_weaver_server`.
pub mod server {
    use super::LocalCounter;
    use std::sync::Arc;
    use wire_weaver_server::{Backend, Connection, Pumps, Serves};

    /// One connection's server: the shared counter and the connection's pumps, where `totals` flows.
    pub struct CounterServer {
        service: Arc<LocalCounter>,
        pumps: Pumps,
    }

    impl CounterServer {
        /// The server of `connection`, forwarding to `service`.
        pub fn new(service: Arc<LocalCounter>, connection: &Connection) -> Self {
            CounterServer {
                service,
                pumps: connection.pumps.clone(),
            }
        }
    }

    impl Serves for CounterServer {
        type Service = LocalCounter;
        type Pumps = Pumps;

        fn service(&self) -> &LocalCounter {
            &self.service
        }

        fn pumps(&self) -> &Pumps {
            &self.pumps
        }
    }

    /// Nothing to send between requests: `totals` is a pump.
    impl Backend for CounterServer {}

    /// What a client checks in link setup.
    pub fn link_config() -> ww_device::LinkConfig<'static> {
        ww_device::LinkConfig::new(
            local_trait_api::COUNTER_API_FULL_GID,
            local_trait_api::COUNTER_API_WIRE_VERSION,
            api_impl::api_hash(),
            api_impl::image_facts(),
            ww_client_server::COMPACT_VERSION,
        )
    }

    pub mod api_impl {
        wire_weaver::ww_codegen!(
            local_trait_api :: CounterApi for super::CounterServer,
            server = true,
            serve_trait = "local_trait_api::Counter",
        );
    }
}

/// The generated client, which implements [Counter] as well.
pub mod client {
    use wire_weaver_client::{ClientConfig, Commander, WwClient};

    pub struct CounterClient {
        pub cmd: Commander,
    }

    impl WwClient for CounterClient {
        fn default_config() -> ClientConfig {
            ClientConfig::default()
        }

        fn try_from_cmd(cmd: Commander) -> Result<Self, wire_weaver_client::Error> {
            Ok(Self { cmd })
        }
    }

    mod api_client {
        wire_weaver::ww_codegen!(
            local_trait_api :: CounterApi for super::CounterClient,
            client = "std_client",
            impl_local_trait = "local_trait_api::Counter",
        );
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use local_trait_api::CounterDyn;
    use std::sync::Arc;
    use tokio::sync::oneshot;
    use wire_weaver_client::in_process::TokioClock;
    use wire_weaver_server::in_process::InProcessListener;
    use wire_weaver_server::{Connection, Server};

    fn expected(name: &str) -> Report {
        Report {
            totals: vec![6, 8],
            step: 2,
            half: 4,
            div_by_zero: true,
            snapshot: SnapshotOwned {
                name: name.to_string(),
                total: 8,
                step: 2,
            },
        }
    }

    /// A counter served on `path` until the returned sender is dropped.
    fn serve(path: &str) -> oneshot::Sender<()> {
        serve_on(InProcessListener::new(path, 4096))
    }

    /// A counter served on `listener` until the returned sender is dropped.
    fn serve_on(listener: InProcessListener) -> oneshot::Sender<()> {
        tests_common::api!(server::api_impl).seed();
        let counter = Arc::new(LocalCounter::new("served"));
        let (stop, stopped) = oneshot::channel::<()>();
        tokio::spawn(async move {
            let make = move |connection: &Connection| {
                server::CounterServer::new(counter.clone(), connection)
            };
            let shutdown = async {
                let _ = stopped.await;
            };
            Server::new(TokioClock::new())
                .serve(server::link_config(), listener, make, shutdown)
                .await
                .expect("serve");
        });
        stop
    }

    async fn connect(path: &str) -> client::CounterClient {
        client::CounterClient::config(|c| {
            c.in_process_path(path.to_owned())
                .resolver(tests_common::resolver())
        })
        .connect()
        .await
        .expect("connect")
    }

    #[tokio::test]
    async fn generic_call_site_on_a_local_struct() {
        let local = LocalCounter::new("local");
        assert_eq!(
            exercise(&local, &CallContext::local()).await.unwrap(),
            expected("local")
        );
    }

    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    async fn generic_call_site_on_the_client() {
        let _stop = serve("local_trait/client");
        let client = connect("local_trait/client").await;
        assert_eq!(
            exercise(&client, &CallContext::local()).await.unwrap(),
            expected("served")
        );
    }

    /// Picked at run time: a trait object of either kind goes through the same call site.
    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    async fn generic_call_site_on_trait_objects() {
        let local: Box<dyn CounterDyn> = Box::new(LocalCounter::new("local"));
        assert_eq!(
            exercise(&local, &CallContext::local()).await.unwrap(),
            expected("local")
        );

        let _stop = serve("local_trait/dyn");
        let remote: Arc<dyn CounterDyn> = Arc::new(connect("local_trait/dyn").await);
        assert_eq!(
            exercise(&remote, &CallContext::local()).await.unwrap(),
            expected("served")
        );
    }

    /// A generic caller can run on another task: the trait's futures are `Send`.
    async fn add_on_a_task<C: Counter + 'static>(counter: Arc<C>, by: u32) -> u32 {
        tokio::spawn(async move { counter.add(&CallContext::local(), by).await.unwrap() })
            .await
            .unwrap()
    }

    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    async fn futures_are_send() {
        assert_eq!(
            add_on_a_task(Arc::new(LocalCounter::new("local")), 5).await,
            5
        );
        let _stop = serve("local_trait/send");
        assert_eq!(
            add_on_a_task(Arc::new(connect("local_trait/send").await), 5).await,
            5
        );
    }

    /// The served counter's policy reads the peer the server forwards: a client on the network may not set the
    /// step, and its call answers `Denied`.
    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    async fn the_peer_reaches_the_service() {
        let addr = "192.0.2.1:4000".parse().unwrap();
        let _stop =
            serve_on(InProcessListener::new("local_trait/peer", 4096).with_peer(Peer::Addr(addr)));
        let client = connect("local_trait/peer").await;
        let cx = CallContext::local();
        let err = Counter::write_step(&client, &cx, 5).await.unwrap_err();
        assert_eq!(err.kind(), ErrorKind::Denied);
        assert_eq!(Counter::read_step(&client, &cx).await.unwrap(), 1);
    }
}

/// Only [Counter] in scope here: with `CounterDyn` too, the calls are ambiguous.
#[cfg(test)]
mod policy_tests {
    use super::*;

    /// A local implementation decides by who asked: the same `CallContext` a server forwards with `cx.call()`.
    #[tokio::test]
    async fn policy_reads_the_peer() {
        let local = LocalCounter::new("local");
        let addr = "192.0.2.1:4000".parse().unwrap();
        let remote = CallContext::new(7).with_peer(Peer::Addr(addr));
        let err = local.write_step(&remote, 5).await.unwrap_err();
        assert_eq!(err.kind(), ErrorKind::Denied);
        assert_eq!(local.read_step(&remote).await.unwrap(), 1);
        local.write_step(&CallContext::local(), 5).await.unwrap();
        assert_eq!(local.read_step(&CallContext::local()).await.unwrap(), 5);
    }
}
