//! Marker types that show API resources in rustdoc.
//!
//! `#[ww_trait]` and `#[ww_api_root]` turn an API trait into a Rust trait of the same name, so that `cargo doc` and
//! docs.rs show it with all its resources and their doc comments. Methods keep their signature, other resources
//! become an associated function returning one of these markers:
//!
//! | API definition                | Shown in rustdoc as                                 |
//! |-------------------------------|-----------------------------------------------------|
//! | `fn led_on(on: bool) -> u8;`  | `fn led_on(on: bool) -> u8`                         |
//! | `property!(rw speed: u32);`   | `fn speed() -> Property<u32>`                       |
//! | `property!(rw mode: M, E);`   | `fn mode() -> Property<M, E>`                       |
//! | `const LIMIT: u32;`           | `fn LIMIT() -> Property<u32>`                       |
//! | `stream!(rx: [u8]);`          | `fn rx() -> Stream<[u8]>`                           |
//! | `sink!(tx: [u8]);`            | `fn tx() -> Sink<[u8]>`                             |
//! | `ww_impl!(gpio: Gpio);`       | `fn gpio() -> impl Gpio`                            |
//! | `stream!(adc[]: u16);`        | `fn adc(index: UNib32) -> Stream<u16>`              |
//!
//! Access mode, flow control and `#[since]` are added to the end of each resource's documentation.
//!
//! The generated trait only describes the API, it is never implemented: server and client code is generated by
//! `ww_codegen!` / `ww_impl!` (see [ww_codegen](crate::ww_codegen)), the markers can't be constructed.

use core::convert::Infallible;
use core::marker::PhantomData;

/// Property of type `T`, read and/or written by a client, `E` is the error a write can fail with, see
/// [properties](https://ww.vhrd.tech/api/properties/).
pub struct Property<T: ?Sized, E = Infallible>(PhantomData<T>, PhantomData<E>);

/// Stream of `T` items from a device to a client, see [streams](https://ww.vhrd.tech/api/streams/).
pub struct Stream<T: ?Sized>(PhantomData<T>);

/// Sink of `T` items from a client to a device, see [streams](https://ww.vhrd.tech/api/streams/).
pub struct Sink<T: ?Sized>(PhantomData<T>);
