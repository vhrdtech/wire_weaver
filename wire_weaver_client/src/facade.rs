//! A facade over clients of several wire lines of one API (CLT-64): [facade!](crate::facade!) and
//! [facade_line!](crate::facade_line!).
//!
//! A host driver that talks to devices of every line still in use has one generated client per line and one type the
//! application sees. [facade!](crate::facade!) takes the operations once and the lines once, and emits:
//!
//! - an enum over the line clients (`enum Thermo { V3(v3::Client), V2(v2::Client), .. }`), the facade itself, with a
//!   `match` per operation: plain `async fn`, no `dyn`, no boxing;
//! - a trait of the operations (`trait Line`), one associated function each, which every line implements for its
//!   client; an operation a line doesn't write answers [Unsupported];
//! - `cmd()`, `wire()`, `config()` and [WwClient](crate::WwClient) with every line's `speaks` and a `try_from_cmd`
//!   that picks the client of the device's line.
//!
//! [facade_line!](crate::facade_line!) is one line's module header: its `Client`, generated by `ww_codegen!`.
//!
//! Streams, sinks and observed properties of a line are converted to the driver's types by the adapters here
//! ([StreamOf], [SplitStreamOf], [ObserverOf], [SinkOf]) and returned boxed ([Updates], [Sends]), since each line's
//! stream type differs. See `docs/evolution/multi_line_host.md`.

use crate::observe::{LevelUpdate, Observer};
use crate::{ClientLine, Commander, StreamError, WwClient};
use std::collections::VecDeque;
use std::future::Future;
use std::pin::Pin;
use wire_weaver::shrink_wrap::{DeserializeShrinkWrapOwned, SerializeShrinkWrapOwned};
pub use wire_weaver::ww_version::WireVersion;

/// An operation of a facade that the device's line doesn't have: what a line's function answers when the line doesn't
/// write it. The driver's error type takes it with `From`.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("{what} is not on this device: it is at wire {device}, {what} needs {needs}")]
pub struct Unsupported {
    /// The operation, by name.
    pub what: &'static str,
    /// The device's wire version.
    pub device: WireVersion,
    /// The lines or revisions that have it, from the operation's `#[unsupported(needs = "..")]`, else
    /// `"another line"`.
    pub needs: &'static str,
}

/// One line's client inside a facade, implemented by [facade_line!](crate::facade_line!).
pub trait LineClient: WwClient + Send + Sync + Sized {
    fn cmd(&self) -> &Commander;

    /// The line this client speaks (the generated `client_line()`).
    fn line() -> ClientLine;

    /// The device's wire version, from link setup.
    fn wire(&self) -> WireVersion {
        self.cmd()
            .device_api_info()
            .user_api_wire
            .expect("link setup refuses a device without a wire version")
    }
}

/// A boxed future of a facade's stream, observer or sink.
pub type Fut<'a, T, E> = Pin<Box<dyn Future<Output = Result<T, E>> + Send + 'a>>;

/// Items of a line's stream or observed property, converted to the driver's type `T`.
pub trait Updates<T, E>: Send {
    fn recv(&mut self) -> Fut<'_, T, E>;
}

/// A line's sink, taking the driver's type `C`.
pub trait Sends<C, E>: Send {
    fn send(&mut self, item: C) -> Fut<'_, (), E>;
}

/// A line's stream of `A`, its items converted by `f`.
pub struct StreamOf<A, T, E> {
    pub stream: crate::Stream<A>,
    pub f: fn(A) -> Result<T, E>,
}

impl<A, T, E> Updates<T, E> for StreamOf<A, T, E>
where
    A: DeserializeShrinkWrapOwned + Send + 'static,
    T: Send + 'static,
    E: From<StreamError> + Send + 'static,
{
    fn recv(&mut self) -> Fut<'_, T, E> {
        Box::pin(async move { (self.f)(self.stream.recv().await?) })
    }
}

/// A line's stream of `A`, each item split into several `T` by `f` (a batch of samples).
pub struct SplitStreamOf<A, T, E> {
    pub stream: crate::Stream<A>,
    pub f: fn(A) -> Result<Vec<T>, E>,
    pending: VecDeque<T>,
}

impl<A, T, E> SplitStreamOf<A, T, E> {
    pub fn new(stream: crate::Stream<A>, f: fn(A) -> Result<Vec<T>, E>) -> Self {
        Self {
            stream,
            f,
            pending: VecDeque::new(),
        }
    }
}

impl<A, T, E> Updates<T, E> for SplitStreamOf<A, T, E>
where
    A: DeserializeShrinkWrapOwned + Send + 'static,
    T: Send + 'static,
    E: From<StreamError> + Send + 'static,
{
    fn recv(&mut self) -> Fut<'_, T, E> {
        Box::pin(async move {
            loop {
                if let Some(item) = self.pending.pop_front() {
                    return Ok(item);
                }
                self.pending = (self.f)(self.stream.recv().await?)?.into();
            }
        })
    }
}

/// A line's observer of a property of type `A`, its values converted by `f`.
pub struct ObserverOf<U: LevelUpdate, A, T, E> {
    pub observer: Observer<U, A>,
    pub f: fn(A) -> Result<T, E>,
}

impl<U, A, T, E> Updates<T, E> for ObserverOf<U, A, T, E>
where
    U: LevelUpdate + Send + 'static,
    U::Latest: Send,
    A: Send + 'static,
    T: Send + 'static,
    E: From<StreamError> + Send + 'static,
{
    fn recv(&mut self) -> Fut<'_, T, E> {
        Box::pin(async move { (self.f)(self.observer.recv().await?.value) })
    }
}

/// A line's sink of `A`, the driver's items `C` converted by `f`.
pub struct SinkOf<A, C, E> {
    pub sink: crate::Sink<A>,
    pub f: fn(C) -> Result<A, E>,
}

impl<A, C, E> Sends<C, E> for SinkOf<A, C, E>
where
    A: SerializeShrinkWrapOwned + Send + 'static,
    C: Send + 'static,
    E: From<StreamError> + Send + 'static,
{
    fn send(&mut self, item: C) -> Fut<'_, (), E> {
        Box::pin(async move {
            let item = (self.f)(item)?;
            Ok(self.sink.send_owned(item).await?)
        })
    }
}

/// One line of a [facade!](crate::facade!): put at the top of the line's module, it emits that line's `Client`,
/// generated from the API root by `ww_codegen!` (`client = "std_client"`, further `ww_codegen!` options after a comma),
/// with [WwClient](crate::WwClient) and [LineClient].
///
/// ```ignore
/// // src/v2.rs
/// wire_weaver_client::facade_line!(thermo_api::wire_v2::Thermo);
///
/// impl crate::Line for Client {
///     async fn read_once(c: &Client) -> Result<model::Sample> {
///         sample(c.read_once().call().await?)
///     }
/// }
/// ```
///
/// The crate needs `wire_weaver` as a dependency, as for any generated client.
#[macro_export]
macro_rules! facade_line {
    ($dep:ident $(:: $seg:ident)+ $(, $($opt:tt)*)?) => {
        /// The generated client of this wire line.
        pub struct Client {
            cmd: $crate::Commander,
        }

        impl $crate::WwClient for Client {
            fn default_config() -> $crate::ClientConfig {
                $crate::ClientConfig::default()
            }

            fn try_from_cmd(cmd: $crate::Commander) -> ::core::result::Result<Self, $crate::Error> {
                Ok(Self { cmd })
            }
        }

        impl $crate::facade::LineClient for Client {
            fn cmd(&self) -> &$crate::Commander {
                &self.cmd
            }

            fn line() -> $crate::ClientLine {
                Client::client_line()
            }
        }

        mod api_client {
            ::wire_weaver::ww_codegen!(
                $dep $(:: $seg)+ for super::Client,
                client = "std_client",
                $($($opt)*)?
            );
        }
    };
}

/// An enum facade over the clients of several wire lines of one API (CLT-64), see [the module](crate::facade).
///
/// ```ignore
/// wire_weaver_client::facade! {
///     /// A thermo device on any line this driver knows.
///     pub enum Thermo {
///         V3(v3::Client),
///         V2(v2::Client),
///     }
///
///     /// The operations, implemented by each line's client.
///     pub trait Line;
///
///     error = Error;
///
///     /// Reads one sample.
///     async fn read_once(&self) -> Sample;
///     /// Lines 2 and 3 from w2.1.
///     #[unsupported(needs = "line 2 from w2.1")]
///     async fn self_test(&self);
/// }
/// ```
///
/// - The variants are listed newest line first: that is the order of `default_config`'s `speaks`. Each line's client
///   comes from [facade_line!](crate::facade_line!).
/// - Each operation becomes a method of the enum returning `Result<T, error>`, and an associated function of the trait,
///   `fn read_once(c: &Self) -> impl Future<Output = Result<Sample, Error>> + Send`, written in each line as `async
///   fn read_once(c: &Client) -> Result<Sample>`. Inside it `c.read_once()` is the generated method: no name clash.
/// - A line that doesn't write an operation answers [Unsupported] (`error` must implement `From<Unsupported>`), with
///   `needs` from the optional `#[unsupported(needs = "..")]` after the operation's doc comment.
/// - An operation's attributes are doc comments only.
/// - `cmd`, `wire` and `config` are taken: no operation may have these names.
#[macro_export]
macro_rules! facade {
    (
        $(#[$enum_attr:meta])*
        $vis:vis enum $Facade:ident $variants:tt

        $(#[$trait_attr:meta])*
        $tvis:vis trait $Line:ident;

        error = $Error:ty;

        $(
            $(#[doc = $doc:literal])*
            $(#[unsupported(needs = $needs:literal)])?
            async fn $op:ident(&self $(, $arg:ident : $ty:ty)* $(,)?) $(-> $ret:ty)?;
        )*
    ) => {
        $(#[$enum_attr])*
        $vis enum $Facade $variants

        $(#[$trait_attr])*
        $tvis trait $Line: $crate::facade::LineClient {
            $(
                $crate::facade!(@default $Error; [$(#[doc = $doc])*] [$($needs)?] $op($($arg: $ty),*) [$($ret)?]);
            )*
        }

        $crate::facade!(@common $Facade $variants);

        impl $Facade {
            $(
                $crate::facade!(
                    @method $Line $variants $Error; [$(#[doc = $doc])*] $op($($arg: $ty),*) [$($ret)?]
                );
            )*
        }
    };

    (@ret) => { () };
    (@ret $ret:ty) => { $ret };

    (@needs) => { "another line" };
    (@needs $needs:literal) => { $needs };

    // the trait's function, answering `Unsupported` unless the line writes it
    (@default $Error:ty; [$($doc:tt)*] [$($needs:literal)?] $op:ident($($arg:ident: $ty:ty),*) [$($ret:ty)?]) => {
        $($doc)*
        #[allow(unused_variables)]
        fn $op(
            c: &Self, $($arg: $ty),*
        ) -> impl ::core::future::Future<
            Output = ::core::result::Result<$crate::facade!(@ret $($ret)?), $Error>
        > + Send {
            let unsupported = $crate::facade::Unsupported {
                what: ::core::stringify!($op),
                device: $crate::facade::LineClient::wire(c),
                needs: $crate::facade!(@needs $($needs)?),
            };
            async move { Err(<$Error as ::core::convert::From<$crate::facade::Unsupported>>::from(unsupported)) }
        }
    };

    // the facade's method, a `match` over the lines
    (@method $Line:ident $variants:tt $Error:ty; [$($doc:tt)*] $op:ident($($arg:ident: $ty:ty),*) [$($ret:ty)?]) => {
        $($doc)*
        pub async fn $op(&self, $($arg: $ty),*) -> ::core::result::Result<$crate::facade!(@ret $($ret)?), $Error> {
            $crate::facade!(@dispatch self $variants $Line $op [$($arg),*])
        }
    };

    (@dispatch $s:ident { $($(#[$vattr:meta])* $Variant:ident($Client:ty)),+ $(,)? } $Line:ident $op:ident $args:tt) => {
        match $s {
            $(Self::$Variant(c) => $crate::facade!(@call c $Client, $Line, $op $args),)+
        }
    };

    (@call $c:ident $Client:ty, $Line:ident, $op:ident [$($arg:ident),*]) => {
        <$Client as $Line>::$op($c, $($arg),*).await
    };

    (@common $Facade:ident { $($(#[$vattr:meta])* $Variant:ident($Client:ty)),+ $(,)? }) => {
        impl $crate::WwClient for $Facade {
            /// Every line this facade has a client of, in the order of its variants.
            fn default_config() -> $crate::ClientConfig {
                $crate::ClientConfig::default()
                    $(.speaks(<$Client as $crate::facade::LineClient>::line()))+
            }

            /// Picks the client of the device's line. Link setup refuses a device on any other line (see
            /// `default_config`), so this fails only on a bug in the facade's own set of clients (CLT-62).
            fn try_from_cmd(cmd: $crate::Commander) -> ::core::result::Result<Self, $crate::Error> {
                let wire = cmd.device_api_info().user_api_wire;
                $(
                    if wire.map(|w| w.line)
                        == Some(<$Client as $crate::facade::LineClient>::line().wire.line)
                    {
                        return Ok(Self::$Variant(<$Client as $crate::WwClient>::try_from_cmd(cmd)?));
                    }
                )+
                Err($crate::Error::NoClientForLine {
                    client: ::core::any::type_name::<Self>(),
                    line: wire,
                    device: ::std::boxed::Box::new(cmd.device_api_info().user_api_version.clone()),
                })
            }
        }

        impl $Facade {
            /// Connect to a device of any line this facade knows; pass the device selection in `c`, e.g.
            /// `config(|c| c.usb().serial_eq(serial))`.
            pub fn config(
                c: impl Fn($crate::ClientConfig) -> $crate::ClientConfig,
            ) -> $crate::PreparedConnection<Self> {
                $crate::PreparedConnection::new(c(<Self as $crate::WwClient>::default_config()))
            }

            pub fn cmd(&self) -> &$crate::Commander {
                match self {
                    $(Self::$Variant(c) => $crate::facade::LineClient::cmd(c),)+
                }
            }

            /// The device's wire version: which line, which revision.
            pub fn wire(&self) -> $crate::facade::WireVersion {
                match self {
                    $(Self::$Variant(c) => $crate::facade::LineClient::wire(c),)+
                }
            }
        }
    };
}
